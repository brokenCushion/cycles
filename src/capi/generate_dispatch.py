"""Generate the private table and forwarding stubs from the public C declarations.

Fail closed on declarations this deliberately small parser does not understand.
No native headers or function signatures are duplicated in the loader.
"""
import hashlib
import re
import sys
from pathlib import Path


def generate(header, destination):
    source = re.sub(r'/\*.*?\*/', '', header.read_text(), flags=re.S)
    declarations = re.findall(r'CCL_API\s+(ccl_status|const char\s*\*)\s*CCL_CALL\s+(ccl_\w+)\s*\(([^;]*)\);', source)
    declarations = [(' '.join(result.split()), name, ' '.join(parameters.split()))
                    for result, name, parameters in declarations]
    assert len(declarations) == source.count('CCL_API ') - source.count('define CCL_API ')
    assert len(declarations) == 95 and len({d[1] for d in declarations}) == 95
    signature = hashlib.sha256(repr(declarations).encode()).hexdigest()
    table = ['/* Generated by generate_dispatch.py; do not edit. */', '#pragma once',
             '#include "cycles_c.h"', f'#define CCL_TABLE_SIGNATURE "{signature}"',
             'struct ccl_backend_table {']
    initializers, forwards = [], []
    special = {'ccl_init', 'ccl_last_error', 'ccl_api_version', 'ccl_has_feature',
               'ccl_set_log_callback', 'ccl_session_params_default'}
    for result, name, parameters in declarations:
        parameters = ' '.join(parameters.split())
        args = [] if parameters == 'void' else parameters.split(',')
        names = []
        for arg in args:
            match = re.fullmatch(r'[\w\s*]+?\b(\w+)', arg.strip())
            assert match, arg
            names.append(match[1])
        table.append(f'  {result} (CCL_CALL *{name})({parameters});')
        initializers.append(f'  &{name},')
        if name not in special:
            forwards.append(f'''{result} CCL_CALL {name}({parameters})
{{
  const auto *api = dispatch.load(std::memory_order_acquire);
  if (!api) return front_fail(CCL_ERROR_NOT_INITIALIZED, "Call ccl_init first");
  front_error = false;
  return api->{name}({', '.join(names)});
}}
''')
    table += ['};', 'typedef const ccl_backend_table *(CCL_CALL *ccl_table_getter)(uint32_t, uint32_t, uint32_t, const char *);']
    destination.mkdir(parents=True, exist_ok=True)
    for name, text in [('dispatch_table.h', '\n'.join(table)),
                       ('dispatch_table.inc', '\n'.join(initializers)),
                       ('dispatch_forward.inc', '\n'.join(forwards))]:
        (destination / name).write_text(text + '\n', encoding='utf-8')


if __name__ == '__main__':
    generate(Path(sys.argv[1]), Path(sys.argv[2]))
